/**
 * Upload-time preflight acceptance: which formats convert, and what a scan is
 * told at upload.
 *
 * **Why this gate runs the real preflight on a real file.** The refusal that
 * matters is the one a user meets, and it is produced by `pdfPreflight` reading
 * page one of a file that was actually uploaded. Asserting the *table entry*
 * (`support.preflight` is a function) would prove nothing about a scan being
 * caught — the failure mode being prevented is a scan that uploads and builds to
 * nothing, and only an end-to-end call can distinguish "caught" from "declared".
 * So the probe runs against `scanned.pdf`, a committed fixture with no text
 * layer, generated by `scripts/gen-parse-fixtures.mjs`.
 *
 * **Why the two extension lists are compared here.** `documents.ts` gates the
 * upload and `extract.ts` decides what happens to it, so a format advertised in
 * one and missing from the other is either an upload that is refused for no
 * stated reason or one that is accepted and then cannot be converted — the
 * "upload succeeds, build produces nothing" shape this task exists to remove.
 * The client page's list is the third copy (it fills the file picker's `accept`
 * attribute); it cannot be imported here because it is bundled for the browser,
 * so it is read as source text and parsed.
 *
 * Runs offline, with no API key: two committed fixtures and a local dependency.
 *
 * Usage: node scripts/verify-parse-preflight.mjs
 */

import { extractionSupport } from '../lib/store/extract.js'
import { ACCEPTED_EXTENSIONS } from '../lib/store/documents.js'
import { readFileSync, readdirSync, rmSync, mkdtempSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

// Imported by URL because this module is loaded after the two above: the host
// operations module pulls in the whole store graph, and a failure there should
// read as one line rather than as a broken import block.
const { KnowledgeOperations } = await import(
  new URL('../lib/host/operations.js', import.meta.url).href
)

let pass = 0
let fail = 0

/**
 * Record one criterion.
 * @param name - what was asserted.
 * @param ok - whether it held.
 * @param detail - the observed value, when failing.
 */
const check = (name, ok, detail = '') => {
  if (ok) {
    pass++
    console.log(`  ok   ${name}`)
  } else {
    fail++
    console.log(`  FAIL ${name}${detail ? ` — ${detail}` : ''}`)
  }
}

/** A PDF with no text layer: what a scan looks like to a converter. */
const SCANNED = 'src/store/parse/fixtures/scanned.pdf'
/** The Latin control: a PDF that certainly has a text layer. */
const LATIN = 'src/store/parse/fixtures/latin.pdf'
/** Two pages: a text-free cover, then a page of text. */
const COVERPAGE = 'src/store/parse/fixtures/coverpage.pdf'
/** `latin.pdf` re-saved with a user password, so opening it needs a password. */
const ENCRYPTED = 'src/store/parse/fixtures/encrypted.pdf'
/** A file that is not a PDF at all. */
const NOT_A_PDF = 'src/store/parse/fixtures/SOURCES.md'

// ---------------------------------------------------------------------------
// 1. What each format's bytes are
// ---------------------------------------------------------------------------
check('md 仍为 verbatim', extractionSupport('a.md').kind === 'verbatim')
check('markdown 仍为 verbatim', extractionSupport('a.markdown').kind === 'verbatim')
check('txt 仍为 verbatim', extractionSupport('a.txt').kind === 'verbatim')
check('pdf 为 converted', extractionSupport('a.pdf').kind === 'converted')
check('docx 为 converted', extractionSupport('a.docx').kind === 'converted')
check('html 为 converted', extractionSupport('a.html').kind === 'converted')
check('htm 为 converted', extractionSupport('a.htm').kind === 'converted')
check('csv 为 converted', extractionSupport('a.csv').kind === 'converted')
check('json 为 converted', extractionSupport('a.json').kind === 'converted')
check('xlsx 为 converted', extractionSupport('a.xlsx').kind === 'converted')
check('无扩展名仍 unsupported', extractionSupport('noext').kind === 'unsupported')
check('未知扩展名仍 unsupported', extractionSupport('a.exe').kind === 'unsupported')

// A `converted` format that names no converter would send the build pipeline to a
// dispatcher with nothing to dispatch to, which is a silent empty build rather
// than the refusal this table exists to give.
const CONVERTERS = {
  '.pdf': 'pdf', '.docx': 'docx', '.html': 'html', '.htm': 'html',
  '.csv': 'csv', '.json': 'json', '.xlsx': 'xlsx',
}
for (const [ext, id] of Object.entries(CONVERTERS)) {
  const support = extractionSupport(`a${ext}`)
  check(`${ext} 指名转换器 ${id}`, support.converter === id, `converter=${support.converter}`)
}
check('verbatim 不指名转换器', extractionSupport('a.md').converter === undefined)
check('unsupported 不指名转换器', extractionSupport('a.exe').converter === undefined)

// ---------------------------------------------------------------------------
// 2. PDF preflight — the scan and the text document must be told apart
// ---------------------------------------------------------------------------
const pdf = extractionSupport('a.pdf')
check('pdf 带预检', typeof pdf.preflight === 'function')

const scan = await pdf.preflight?.(SCANNED)
check('扫描件上传期被拒', scan?.ok === false, JSON.stringify(scan))
check('扫描件 remedy 提到 OCR', /OCR/.test(scan?.remedy ?? ''), scan?.remedy ?? '(no remedy)')
// The remedy is the user's only guidance, so it must also say what to do: "this
// plugin has no OCR" without "run one yourself first" leaves them stuck.
check(
  '扫描件 remedy 说明要先离线 OCR',
  /先/.test(scan?.remedy ?? '') && /离线/.test(scan?.remedy ?? ''),
  scan?.remedy ?? '(no remedy)',
)

const control = await pdf.preflight?.(LATIN)
check('有文本层的 PDF 通过预检', control?.ok === true, JSON.stringify(control))

// A document whose *cover* has no text is not a scan. Measured over eighteen real
// PDFs on this machine, two carry their first text on page 2 — a page-one-only
// probe refuses both, and the remedy it gives ("run OCR") is wrong advice about a
// document with a perfectly good text layer. This is the assertion that pins how
// many pages the probe must look at before it may call a document a scan.
const cover = await pdf.preflight?.(COVERPAGE)
check('正文从第 2 页开始的 PDF 通过预检', cover?.ok === true, JSON.stringify(cover))

// A file that is not a PDF at all must be refused rather than throw: the only
// remedy for a broken upload is to upload something else.
const broken = await pdf.preflight?.(NOT_A_PDF)
check('非 PDF 文件预检被拒而非抛错', broken?.ok === false, JSON.stringify(broken))

// An encrypted PDF must be refused with the "export a copy without the password"
// remedy, and it must be *recognised as encrypted* rather than caught as a
// generic open failure — the two need different user actions, and the sentence
// "无法打开" sends the user to re-export a file that is perfectly intact.
//
// This fixture is the one file in this directory that could not be regenerated by
// `gen-parse-fixtures.mjs`: pdf-lib **cannot write** an encrypted PDF (it reads
// them, holding only `Encrypt`-dict detection), so the file was produced once
// with `pypdf` and committed. `SOURCES.md` records the exact command.
const locked = await pdf.preflight?.(ENCRYPTED)
check('加密 PDF 上传期被拒', locked?.ok === false, JSON.stringify(locked))
check('加密 PDF remedy 提到口令', /口令/.test(locked?.remedy ?? ''), locked?.remedy ?? '(no remedy)')
check('加密 PDF remedy 说明导出去权限副本', /副本/.test(locked?.remedy ?? ''), locked?.remedy ?? '(no remedy)')

// ---------------------------------------------------------------------------
// 3. Only genuinely unsolvable entries remain `needs-conversion`
// ---------------------------------------------------------------------------
const everyEntry = [...ACCEPTED_EXTENSIONS].map(ext => [`${ext}`, extractionSupport(`a.${ext}`)])
const stuck = everyEntry.filter(([, support]) => support.kind === 'needs-conversion')
check(
  '清单内没有会静默产出空索引的 needs-conversion 条目',
  stuck.length === 0 || stuck.every(([, support]) => (support.remedy ?? '') !== ''),
  stuck.map(([ext]) => ext).join(', ') || '(none)',
)
// Unknown extensions are `unsupported`, never `needs-conversion`: there is no
// remedy to name for a format nobody claims to handle.
check(
  'unsupported 不携带 remedy',
  extractionSupport('a.exe').remedy === undefined && extractionSupport('noext').remedy === undefined,
)

// ---------------------------------------------------------------------------
// 4. The three extension lists are one list
// ---------------------------------------------------------------------------
/** Keys of the support table, which must be exactly the advertised extensions. */
const supportKeys = [...ACCEPTED_EXTENSIONS].filter(ext => extractionSupport(`a.${ext}`).kind !== 'unsupported')
check(
  'documents.ts 的清单每一项都能被 extract.ts 处理',
  supportKeys.length === ACCEPTED_EXTENSIONS.length,
  ACCEPTED_EXTENSIONS.filter(ext => extractionSupport(`a.${ext}`).kind === 'unsupported').join(', ') || '(none)',
)

/**
 * Read the client page's own `ACCEPTED_EXTENSIONS`.
 *
 * Parsed from source rather than imported because the page is browser code: the
 * compiled bundle for it is not loadable from a plain Node gate (it imports
 * React and the slot library). The declaration is a flat `as const` array, so
 * matching the literal is enough — and if someone changes its shape, this throws
 * rather than silently passing.
 * @returns the client page's extension list.
 */
function clientExtensions() {
  const source = readFileSync('src/client/pages/DocumentsPage.tsx', 'utf8')
  const declaration = /export const ACCEPTED_EXTENSIONS = \[([^\]]*)\]/.exec(source)
  if (declaration === null) throw new Error('DocumentsPage.tsx 中找不到 ACCEPTED_EXTENSIONS 的声明')
  return [...(declaration[1] ?? '').matchAll(/'([^']+)'/g)].map(match => match[1])
}

const client = clientExtensions()
check(
  'DocumentsPage.tsx 的清单与 documents.ts 一致',
  client.length === ACCEPTED_EXTENSIONS.length && client.every((ext, i) => ext === ACCEPTED_EXTENSIONS[i]),
  `client=${client.join('/')} store=${ACCEPTED_EXTENSIONS.join('/')}`,
)
check(
  'DocumentsPage.tsx 的清单与 SUPPORT 键集一致',
  client.every(ext => extractionSupport(`a.${ext}`).kind !== 'unsupported'),
  client.filter(ext => extractionSupport(`a.${ext}`).kind === 'unsupported').join(', ') || '(none)',
)

// ---------------------------------------------------------------------------
// 5. The refusal reaches the user through the path they actually take
// ---------------------------------------------------------------------------
{
  // The probe's answer only matters if `addDocumentStream` asks for it. This
  // drives a real upload of `scanned.pdf` into a temp store and asserts that the
  // refusal is what comes back — no record, no stored original, and a remedy
  // naming OCR. Without this the gate would pass with the probe wired to nothing.
  const workspace = mkdtempSync(join(tmpdir(), 'kb-preflight-'))
  const ops = new KnowledgeOperations({ workspaceDir: workspace, stateDir: '.dsh-kb-preflight' })
  // A real collection id shape: the store validates `kb_<domain>_<4 hex>`.
  const collection = 'kb_test_9f3c'
  await ops.createCollection({ name: '预检', collectionId: collection, description: '' })

  const bytes = readFileSync(SCANNED)
  const upload = () =>
    ops.addDocumentStream(collection, '扫描件.pdf', bytes.byteLength, (async function* () { yield bytes })())

  let message = ''
  try {
    await upload()
  } catch (error) {
    message = error instanceof Error ? error.message : String(error)
  }
  check('上传接口拒绝扫描件', message !== '', message === '' ? 'the upload was accepted' : message)
  check('拒绝文案提到 OCR', /OCR/.test(message), message)

  const sources = join(ops.storeRoot, collection, 'sources')
  const records = existsSync(sources) ? readdirSync(sources) : []
  check('被拒的上传没有留下原件', records.length === 0, records.join(', ') || '(sources/ is empty)')
  rmSync(workspace, { recursive: true, force: true })
}

console.log(`\n${pass} passed, ${fail} failed`)
process.exit(fail === 0 ? 0 : 1)